import json
from pathlib import Path
from datetime import datetime
from typing import List, Dict, Any
from src.state import GraphState, Requirement, BlacklistedRequirement, AuditFeedback

PRIORITY_SCALE_EXPLANATION = """
### Priority Scale Explanation (MoSCoW Method - OS6)

The requirements in this specification are prioritized using the internationally recognized MoSCoW method:

1. **Must Have (P1 - Critical)**:
   - Non-negotiable capabilities essential for the fundamental operation, security, or legal/regulatory compliance of the Evergreen Integrated Library System. Without these, the system cannot be deployed or operated safely (e.g., core database transactional integrity, staff authentication, basic catalog search and item checkout).

2. **Should Have (P2 - High Priority)**:
   - Highly important capabilities that provide significant business value, workflow automation, or essential operational reporting. They are not strictly blockers for a minimal prototype, but are required for normal day-to-day production usage across library branches (e.g., automated overnight batch reporting, bulk item transfer interfaces).

3. **Could Have (P3 - Desirable / Medium Priority)**:
   - Useful enhancements, ergonomic interface conveniences, and optional customization features that improve staff efficiency or patron experience if time and development resources permit (e.g., custom color coding on reports, export to obscure file formats).

4. **Won't Have (P4 - Out of Scope / Deferred)**:
   - Features identified during stakeholder discussions that will not be implemented in the current development cycle or that have been deferred to future Evergreen releases.
"""

def generate_markdown_document(
    requirements: List[Requirement],
    blacklisted: List[BlacklistedRequirement],
    feedback: AuditFeedback,
    iterations: int,
    total_docs: int
) -> str:
    """Formats the consolidated requirements into a professional SRS document (OS1-OS9)."""
    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    
    # Sort requirements by ID
    reqs_sorted = sorted(requirements, key=lambda x: x.id)
    
    # Priority counts
    p_counts = {"Must Have": 0, "Should Have": 0, "Could Have": 0, "Won't Have": 0}
    for r in reqs_sorted:
        p_counts[r.priority] = p_counts.get(r.priority, 0) + 1
    
    lines = []
    lines.append("# Software Requirements Specification (SRS)")
    lines.append("## Evergreen Integrated Library System (ILS) - Requirements Consolidation")
    lines.append("")
    lines.append(f"> **Generated by**: Agentic Requirements Refinement Network (LangGraph)")  
    lines.append(f"> **Date**: {now}  ")
    lines.append(f"> **Input Corpus Size**: {total_docs} documents processed  ")
    lines.append(f"> **Consolidated Requirements**: {len(reqs_sorted)}  ")
    lines.append(f"> **Blacklisted / Discarded Proposals**: {len(blacklisted)}  ")
    lines.append(f"> **Feedback Loop Iterations**: {iterations}  ")
    if feedback:
        lines.append(f"> **Audit Quality Score**: {feedback.score}/100 ({'Approved' if feedback.approved else 'Conditional'})  ")
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("## 1. Introduction and Architectural Overview")
    lines.append(
        "This specification consolidates requirements for the Evergreen Integrated Library System (ILS) "
        "derived from raw stakeholder inputs, including librarian interviews, technical subcommittee meeting "
        "minutes, system administrator consultations, and email discussions. "
        "All requirements have been normalized, checked for semantic deduplication, categorized, and traced "
        "to their source documentation."
    )
    lines.append("")
    lines.append(PRIORITY_SCALE_EXPLANATION.strip())
    lines.append("")
    lines.append("### Requirements Summary by Priority")
    lines.append("| Priority Level | Count | Description |")
    lines.append("| :--- | :--- | :--- |")
    lines.append(f"| **Must Have** | {p_counts.get('Must Have', 0)} | Essential core system capabilities |")
    lines.append(f"| **Should Have** | {p_counts.get('Should Have', 0)} | Important operational and reporting capabilities |")
    lines.append(f"| **Could Have** | {p_counts.get('Could Have', 0)} | Ergonomic enhancements and conveniences |")
    wont_count = p_counts.get("Won't Have", 0)
    lines.append(f"| **Won't Have** | {wont_count} | Deferred or low-priority features |")
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("## 2. Master Requirements Table")
    lines.append("| ID | Title | Priority | Category | Source Documents |")
    lines.append("| :--- | :--- | :--- | :--- | :--- |")
    for r in reqs_sorted:
        srcs = ", ".join(f"`{s}`" for s in r.source_documents)
        lines.append(f"| **{r.id}** | {r.title} | `{r.priority}` | {r.category} | {srcs} |")
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("## 3. Detailed Requirements Catalog (OS2, OS4, OS5, OS6, OS7, OS8)")
    lines.append("")
    
    # Group by category
    categories: Dict[str, List[Requirement]] = {}
    for r in reqs_sorted:
        categories.setdefault(r.category, []).append(r)
    
    for cat_name, cat_reqs in sorted(categories.items()):
        lines.append(f"### Subsystem: {cat_name}")
        lines.append("")
        for r in cat_reqs:
            lines.append(f"#### [{r.id}] {r.title}")
            lines.append(f"- **Priority**: `{r.priority}`")
            lines.append(f"- **Category**: {r.category}")
            lines.append(f"- **Traceability (Source Documents)**: " + ", ".join(f"`{s}`" for s in r.source_documents))
            if r.rationale:
                lines.append(f"- **Architectural Rationale**: {r.rationale}")
            lines.append("")
            lines.append("**Description & System Behavior:**")
            lines.append(r.description)
            lines.append("")
            lines.append("---")
            lines.append("")
            
    lines.append("## 4. Blacklisted and Discarded Proposals (OS9)")
    lines.append(
        "This section documents proposals, candidate requirements, or conflicting suggestions that were "
        "explicitly analyzed and discarded during refinement. For complete governance transparency, each item "
        "records the source documents where it arose and the engineering rationale for its exclusion."
    )
    lines.append("")
    if blacklisted:
        lines.append("| Blacklist ID | Title | Reason for Discarding | Originating Sources |")
        lines.append("| :--- | :--- | :--- | :--- |")
        for b in blacklisted:
            srcs = ", ".join(f"`{s}`" for s in b.source_documents)
            lines.append(f"| **{b.id}** | {b.title} | {b.reason_for_discarding} | {srcs} |")
        lines.append("")
        for b in blacklisted:
            lines.append(f"### [{b.id}] {b.title}")
            lines.append(f"- **Sources**: " + ", ".join(f"`{s}`" for s in b.source_documents))
            lines.append(f"- **Reason for Discarding**: {b.reason_for_discarding}")
            lines.append("")
            lines.append("**Original Statement / Description:**")
            lines.append(b.description)
            lines.append("")
    else:
        lines.append("*(No requirements were blacklisted in this refinement run)*")
        lines.append("")
    
    lines.append("---")
    lines.append("## 5. Automated Quality Audit Log (ANS3 Feedback Verification)")
    if feedback:
        lines.append(f"- **Audit Status**: {'APPROVED' if feedback.approved else 'REVISION REQUIRED'}")
        lines.append(f"- **Quality Audit Score**: {feedback.score} / 100")
        if feedback.issues:
            lines.append("- **Issues Evaluated**:")
            for issue in feedback.issues:
                lines.append(f"  - {issue}")
        if feedback.suggestions:
            lines.append("- **Auditor Recommendations Applied**:")
            for sug in feedback.suggestions:
                lines.append(f"  - {sug}")
    lines.append("")
    lines.append("---")
    lines.append("*End of Requirements Specification*")
    
    return "\n".join(lines)

def build_graph_data(
    requirements: List[Requirement],
    blacklisted: List[BlacklistedRequirement],
    documents: List[Any]
) -> Dict[str, Any]:
    """Prepares structured graph data (nodes & edges) for interactive PyVis visualization."""
    nodes = []
    edges = []
    
    # 1. Document Nodes (Color: Light Blue)
    doc_names = set()
    for doc in documents:
        dname = doc.file_name if hasattr(doc, "file_name") else str(doc)
        doc_names.add(dname)
        nodes.append({
            "id": f"DOC:{dname}",
            "label": dname,
            "group": "document",
            "title": f"Source Document: {dname}",
            "shape": "box",
            "color": "#3498db" # Blue
        })
    
    # Color mapping for priorities
    priority_colors = {
        "Must Have": "#e74c3c",   # Red / High urgency
        "Should Have": "#f39c12", # Orange / Medium urgency
        "Could Have": "#2ecc71",  # Green / Desirable
        "Won't Have": "#95a5a6"   # Light grey
    }
    
    # 2. Requirement Nodes
    for r in requirements:
        req_node_id = f"REQ:{r.id}"
        p_color = priority_colors.get(r.priority, "#9b59b6")
        nodes.append({
            "id": req_node_id,
            "label": f"[{r.id}] {r.title[:25]}...",
            "group": r.priority,
            "title": f"<b>{r.id}: {r.title}</b><br>Priority: {r.priority}<br>Category: {r.category}<br><p>{r.description[:200]}...</p>",
            "shape": "dot",
            "size": 20,
            "color": p_color,
            "full_data": r.model_dump()
        })
        
        # Edges from Document to Requirement (Traceability links)
        for src in r.source_documents:
            doc_id = f"DOC:{src}"
            if src not in doc_names:
                # Add node if missing
                nodes.append({
                    "id": doc_id,
                    "label": src,
                    "group": "document",
                    "title": f"Source Document: {src}",
                    "shape": "box",
                    "color": "#3498db"
                })
                doc_names.add(src)
            edges.append({
                "from": doc_id,
                "to": req_node_id,
                "title": f"Derivation: {src} -> {r.id}",
                "color": "#bdc3c7"
            })
            
    # 3. Blacklist Nodes (Color: Dark Grey / Brown)
    for b in blacklisted:
        blk_node_id = f"BLK:{b.id}"
        nodes.append({
            "id": blk_node_id,
            "label": f"[{b.id}] {b.title[:22]}...",
            "group": "Blacklist",
            "title": f"<b>[DISCARDED] {b.id}: {b.title}</b><br>Reason: {b.reason_for_discarding}",
            "shape": "triangleDown",
            "size": 18,
            "color": "#7f8c8d",
            "full_data": b.model_dump()
        })
        for src in b.source_documents:
            doc_id = f"DOC:{src}"
            edges.append({
                "from": doc_id,
                "to": blk_node_id,
                "title": f"Discarded derivation: {src} -> {b.id}",
                "dashes": True,
                "color": "#95a5a6"
            })

    return {"nodes": nodes, "edges": edges}

def builder_node(state: GraphState) -> dict:
    """
    Deterministic Node (ANS2):
    Formats requirements and blacklist into a final Markdown specification (OS1)
    and produces graph visualization data.
    """
    reqs = state.get("consolidated_requirements", [])
    blacklisted = state.get("blacklisted_requirements", [])
    feedback = state.get("audit_feedback")
    iteration = state.get("iteration", 1)
    documents = state.get("documents", [])
    
    final_doc = generate_markdown_document(
        requirements=reqs,
        blacklisted=blacklisted,
        feedback=feedback,
        iterations=iteration,
        total_docs=len(documents)
    )
    
    graph_data = build_graph_data(
        requirements=reqs,
        blacklisted=blacklisted,
        documents=documents
    )
    
    # Save default output artifacts locally
    out_path = Path("requirements.md")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(final_doc)
        
    graph_path = Path("requirements_graph.json")
    with open(graph_path, "w", encoding="utf-8") as f:
        json.dump(graph_data, f, indent=2)
    
    log_msg = (
        f"[Builder Node] Successfully compiled SRS document ({len(final_doc.splitlines())} lines) "
        f"and graph data ({len(graph_data['nodes'])} nodes, {len(graph_data['edges'])} edges) (Deterministic node - ANS2)."
    )
    print(log_msg)
    
    return {
        "final_document": final_doc,
        "graph_data": graph_data,
        "logs": state.get("logs", []) + [log_msg]
    }
